<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Enums\PermissionEnum;
use App\Enums\RoleEnum;
use App\Models\Role;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Spatie\Permission\Models\Permission;
use Spatie\Permission\PermissionRegistrar;

/**
 * Syncs {@see PermissionEnum} into the database and writes `resources/js/enums/permission-enum.ts`.
 * Also ensures the built-in {@see RoleEnum} roles exist with their default permissions (excubia shape).
 */
#[Signature('signaculum:sync-permissions {--prune : Remove permissions that are no longer defined in PermissionEnum}')]
#[Description('Sync PermissionEnum to the database and generate the TypeScript enum')]
final class SyncPermissionsCommand extends Command
{
    public function handle(): int
    {
        app(PermissionRegistrar::class)->forgetCachedPermissions();

        $guard = (string) config('auth.defaults.guard', 'web');
        $enumValues = PermissionEnum::values();
        $createdNames = [];

        foreach (PermissionEnum::cases() as $permissionEnum) {
            $permission = Permission::query()->firstOrCreate(
                ['name' => $permissionEnum->value, 'guard_name' => $guard],
            );

            if ($permission->wasRecentlyCreated) {
                $createdNames[] = $permissionEnum->value;
            }
        }

        $this->info(sprintf('Synced %d permissions.', count($enumValues)));
        $this->ensureBuiltInRoles($guard, $createdNames);

        if ($this->option('prune')) {
            $deleted = Permission::query()
                ->where('guard_name', $guard)
                ->whereNotIn('name', $enumValues)
                ->delete();

            $this->info(sprintf('Pruned %d stale permissions.', $deleted));
        }

        $this->generateTypeScriptEnum();
        app(PermissionRegistrar::class)->forgetCachedPermissions();

        return self::SUCCESS;
    }

    /**
     * Create RoleEnum rows and keep their default permission sets in sync. Newly created
     * permissions are also granted to an existing `admin` role (externa upgrade behaviour).
     *
     * @param  list<string>  $createdNames
     */
    private function ensureBuiltInRoles(string $guard, array $createdNames): void
    {
        foreach (RoleEnum::cases() as $roleEnum) {
            $role = Role::query()->firstOrCreate(
                ['name' => $roleEnum->value, 'guard_name' => $guard],
                [
                    'is_system' => $roleEnum === RoleEnum::SuperAdmin,
                    'is_assignable' => true,
                ],
            );

            $role->syncPermissions(array_map(
                fn (PermissionEnum $permission): string => $permission->value,
                $roleEnum->defaultPermissions(),
            ));
        }

        if ($createdNames === []) {
            return;
        }

        $admin = Role::query()
            ->where('name', RoleEnum::Admin->value)
            ->where('guard_name', $guard)
            ->first();

        if ($admin === null) {
            return;
        }

        $admin->givePermissionTo($createdNames);
        $this->info(sprintf(
            'Granted %d new permission(s) to %s: %s',
            count($createdNames),
            RoleEnum::Admin->value,
            implode(', ', $createdNames),
        ));
    }

    /**
     * Write the generated PermissionEnum TypeScript file for `useCan()`.
     */
    private function generateTypeScriptEnum(): void
    {
        $lines = [
            '/**',
            ' * Auto-generated by `php artisan signaculum:sync-permissions`. Do not edit manually.',
            ' */',
            'export enum PermissionEnum {',
        ];

        foreach (PermissionEnum::cases() as $case) {
            $lines[] = sprintf("    %s = '%s',", $case->name, $case->value);
        }

        $lines[] = '}';
        $lines[] = '';

        $path = resource_path('js/enums/permission-enum.ts');
        File::ensureDirectoryExists(dirname($path));
        File::put($path, implode(PHP_EOL, $lines).PHP_EOL);

        $this->info("Generated {$path}");
    }
}
